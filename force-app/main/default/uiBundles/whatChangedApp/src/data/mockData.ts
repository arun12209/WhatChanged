const now = new Date();

function getIsoOffset(minutesAgo: number): string {
  return new Date(now.getTime() - minutesAgo * 60 * 1000).toISOString();
}

function getFormattedTime(minutesAgo: number): string {
  const d = new Date(now.getTime() - minutesAgo * 60 * 1000);
  return d.toLocaleTimeString([], { hour: 'numeric', minute: '2-digit', hour12: true });
}

function getRelativeTime(minutesAgo: number): string {
  if (minutesAgo < 1) return 'Just now';
  if (minutesAgo === 1) return '1 min ago';
  if (minutesAgo < 60) return `${minutesAgo} mins ago`;
  const hours = Math.floor(minutesAgo / 60);
  if (hours === 1) return '1 hour ago';
  if (hours < 24) return `${hours} hours ago`;
  const days = Math.floor(hours / 24);
  if (days === 1) return 'Yesterday';
  return `${days} days ago`;
}

